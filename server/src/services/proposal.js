// 模板回退：根据输入生成结构化开题报告
export function genProposalBuiltin(params) {
  const {
    topic = '研究主题',
    field = '本学科领域',
    direction = '',
    keywords = [],
    objective = '',
    method = '',
    innovation = '',
  } = params;

  const kw = Array.isArray(keywords) ? keywords : String(keywords || '').split(/[,，\s]+/).filter(Boolean);
  const kwStr = kw.length ? kw.join('、') : '（关键词待补充）';

  const sections = [];

  sections.push(`# ${topic}开题报告\n`);

  sections.push(`## 一、研究背景与意义
近年来，${field}领域的相关研究受到学术界与产业界的广泛关注。${topic}作为该领域中的重要议题，其研究价值日益凸显。从理论层面看，本课题有助于丰富${field}的理论体系，深化对${kwStr}等核心概念的理解；从实践层面看，研究成果可为相关行业提供决策参考与方法支撑，具有较强的现实意义。

在国际范围内，相关研究起步较早，已形成较为系统的理论框架。而国内研究虽起步稍晚，但近年来发展迅速，特别是在${direction || '应用层面'}取得了显著进展。然而，现有研究在系统性、深度和前瞻性方面仍存在不足，本课题的开展具有重要的理论与实践价值。`);

  sections.push(`## 二、国内外研究现状
### 2.1 国外研究现状
国外学者围绕${topic}开展了大量研究，主要集中在以下几个方面：一是理论建构层面，相关研究系统梳理了${kwStr}的理论脉络；二是实证分析层面，已有研究采用多种方法对研究问题进行了检验；三是应用拓展层面，相关成果已在多个领域得到验证。

### 2.2 国内研究现状
国内研究在借鉴国外理论的基础上，结合本土实际开展了富有特色的工作。近年来，学者们在${field}领域取得了重要进展，但仍存在以下问题：（1）研究视角相对单一；（2）实证研究样本有限；（3）跨学科融合不足。

### 2.3 研究述评
综合国内外研究现状可以看出，已有成果为本课题提供了坚实的理论基础和方法借鉴，但在${kwStr}等核心议题上仍有进一步拓展的空间。`);

  sections.push(`## 三、研究目标与拟解决的关键问题
### 3.1 研究目标
本研究旨在${objective || `围绕${topic}展开系统研究，揭示其内在规律与作用机制，构建相应的分析框架，并通过实证方法对核心假设进行检验，最终提出具有理论价值与实践意义的结论和建议`}。

### 3.2 拟解决的关键问题
1. ${kwStr}的核心概念界定与测量指标构建；
2. 影响因素的识别与作用机制分析；
3. 研究模型的构建与实证检验；
4. 政策建议与管理启示的提炼。`);

  sections.push(`## 四、研究内容
本课题的研究内容主要包括以下五个方面：

1. **理论基础与文献综述**：系统梳理${field}领域的相关理论与文献，明确研究边界与切入点。
2. **概念界定与变量测量**：对${kwStr}等核心变量进行操作化定义，构建测量量表。
3. **研究模型构建**：基于理论分析提出研究假设，构建概念模型。
4. **实证研究设计**：确定样本选取、数据收集与分析方法，开展实证检验。
5. **结论与建议**：归纳研究发现，提出理论与实践建议，并指出研究局限与未来方向。`);

  sections.push(`## 五、研究方法与技术路线
### 5.1 研究方法
本研究采用定性与定量相结合的混合研究方法：
- **文献研究法**：系统梳理国内外相关文献，奠定理论基础；
- **案例分析法**：选取典型案例进行深入剖析；
- **问卷调查法**：通过结构化问卷收集数据；
- **统计分析法**：运用 SPSS / AMOS 等工具进行实证分析。${method ? `\n\n本课题还将结合${method}方法，以增强研究结论的可靠性。` : ''}

### 5.2 技术路线
文献综述 → 理论建构 → 概念界定 → 模型构建 → 假设提出 → 问卷设计 → 数据收集 → 实证分析 → 结论提炼 → 建议输出`);

  sections.push(`## 六、创新点与特色
本研究的创新之处主要体现在：

1. **理论创新**：在${field}领域已有研究基础上，提出新的理论分析框架，拓展了${kwStr}的研究视角；
2. **方法创新**：综合运用多种研究方法，弥补单一方法的局限；
3. **应用创新**：研究成果具有较强的实践指导意义，可为相关决策提供参考。${innovation ? `\n\n此外，${innovation}也是本课题的重要特色。` : ''}`);

  sections.push(`## 七、研究计划与进度安排
本课题预计研究周期为 12 个月，具体安排如下：

| 阶段 | 时间 | 主要工作 |
| --- | --- | --- |
| 第一阶段 | 第 1-2 月 | 文献收集与综述、理论梳理 |
| 第二阶段 | 第 3-4 月 | 概念界定、模型构建、假设提出 |
| 第三阶段 | 第 5-7 月 | 问卷设计、预调研、正式调研 |
| 第四阶段 | 第 8-10 月 | 数据分析、假设检验 |
| 第五阶段 | 第 11-12 月 | 论文撰写、修改完善、答辩准备 |`);

  sections.push(`## 八、预期成果
1. 完成《${topic}研究》学位论文 1 篇；
2. 形成系统的研究报告 1 份；
3. 在核心期刊发表学术论文 1-2 篇；
4. 提出具有理论与实践价值的研究结论与政策建议。`);

  sections.push(`## 九、参考文献
[1] 张某某. ${field}基础理论研究[J]. 学术期刊, 2023, 12(3): 45-58.
[2] Smith J, Brown K. A study on ${topic}[J]. Journal of Academic Research, 2022, 15(2): 112-125.
[3] 李某某, 王某某. ${kwStr}研究综述[J]. 中国学术研究, 2023, 8(4): 78-92.
[4] Wilson R, Davis M. Theoretical Framework and Empirical Analysis[M]. New York: Academic Press, 2021.
[5] 陈某某. ${direction || field}前沿问题研究[J]. 学术月刊, 2024, 56(1): 23-37.

（注：以上为示例参考文献，实际撰写时请根据查阅的真实文献进行替换）`);

  sections.push(`## 十、研究基础与条件
研究者已系统学习${field}相关理论与方法，具备开展本课题研究的基础知识与能力。已收集一定数量的国内外文献资料，掌握 SPSS、AMOS、Python 等数据分析工具。所在单位图书馆、数据库资源丰富，能够满足本课题的文献查阅与数据获取需求。同时，导师与同行专家可提供专业的学术指导。`);

  return sections.join('\n\n');
}

// 真实 AI 调用时的 user prompt 构造
export function buildProposalUserPrompt(params) {
  const {
    topic, field, direction, keywords, objective, method, innovation,
  } = params;
  const kw = Array.isArray(keywords) ? keywords.join('、') : (keywords || '');
  return `请生成一份完整的开题报告。

【论文题目】${topic}
【学科领域】${field}
【研究方向】${direction || '（未指定）'}
【关键词】${kw || '（待补充）'}
【研究目标】${objective || '（请根据题目自动生成）'}
【研究方法】${method || '（请自动选择合适方法）'}
【创新点】${innovation || '（请自动提炼）'}

请按以下 10 个章节生成，每章节内容详实，符合学术规范：
1. 研究背景与意义
2. 国内外研究现状
3. 研究目标与拟解决的关键问题
4. 研究内容
5. 研究方法与技术路线
6. 创新点与特色
7. 研究计划与进度安排
8. 预期成果
9. 参考文献（至少 5 条）
10. 研究基础与条件

使用 Markdown 格式输出，章节用 "## " 开头。`;
}

